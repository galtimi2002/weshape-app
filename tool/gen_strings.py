#!/usr/bin/env python3
"""Writes lib/core/i18n/strings/strings_<code>.dart from tool/translations.py.

    python3 tool/gen_strings.py

Stops if any language is missing a key, has an extra one, or drops the
{name} placeholder from the greeting.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tool"))
from translations import T  # noqa: E402

source = (ROOT / "lib/core/i18n/app_strings.dart").read_text(encoding="utf-8")
keys = re.findall(r"required this\.(\w+),", source)

problems = []
for lang, strings in T.items():
    missing = [k for k in keys if k not in strings]
    extra = [k for k in strings if k not in keys]
    if missing:
        problems.append(f"{lang}: missing {missing}")
    if extra:
        problems.append(f"{lang}: unknown {extra}")
    if "{name}" not in strings.get("greeting", ""):
        problems.append(f"{lang}: greeting lacks {{name}}")
    empty = [k for k, v in strings.items() if not v.strip()]
    if empty:
        problems.append(f"{lang}: empty {empty}")
if problems:
    sys.exit("\n".join(problems))


def dart(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


out_dir = ROOT / "lib/core/i18n/strings"
out_dir.mkdir(parents=True, exist_ok=True)
for lang, strings in T.items():
    lines = [
        "// GENERATED by tool/gen_strings.py from tool/translations.py. Do not edit.",
        "",
        "import '../app_strings.dart';",
        "",
        f"const AppStrings kStrings{lang[0].upper()}{lang[1:]} = AppStrings(",
        *[f"  {k}: {dart(strings[k])}," for k in keys],
        ");",
        "",
    ]
    (out_dir / f"strings_{lang}.dart").write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {len(T)} languages x {len(keys)} strings")
